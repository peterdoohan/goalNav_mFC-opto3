def get_events_df(session_dir):
    """Creates a dataframe with all states and events from a pycontrol session"""
    session_df = load_session_dataframe(session_dir.pycontrol_path, pair_end_suffix="_out")
    # remove rsync and print variable events
    events_df = session_df[
        (session_df.subtype != "sync") & (session_df.type != "info") & (session_df.type != "variable")
    ]
    events_df.reset_index(drop=True, inplace=True)
    return events_df


def get_trials_df(session_dir):
    """
    Creates a dataframe with all trial events from raw pycontrol data (path input).

    Rows of the output dataframe are:
    - trial(int): trial number
    - goal(str, alphanumerical): goal location active during trial
    - errors(int): number of non-goal ports poked during trial, see _get_errors function for more details
    - time, cue (float): time of cue onset
    - time, reward (float): time of reward delivery
    - time, end_reward_consumption (float): time of last poke out of reward port (can be after start of next trial)
    - time, ITI_start (float): time of ITI onset
    - time, trial_end (float): time of next trial
    """
    session_df = load_session_dataframe(session_dir.pycontrol_path)
    session_end_time = session_df.time.iloc[-1]
    print_variables_df = pd.DataFrame(session_df[session_df.subtype == "print"].content.to_list())
    stim_trials = print_variables_df.stim_trial.astype(bool)
    # calc trials since stim
    stim_group = stim_trials.cumsum()
    trials_since_stim = stim_group.groupby(stim_group).cumcount()
    trials_since_stim[stim_trials] = np.nan
    trials_since_stim[stim_group == 0] = np.nan  # before first stim trial
    # calc consecutive stim trials
    _groups = (stim_trials != stim_trials.shift()).cumsum()
    consecutive_stim_trials = stim_trials.groupby(_groups).cumsum().where(stim_trials, np.nan)
    # get stim times
    stim_start_times = [i / 1000 if i is not None else np.nan for i in print_variables_df.stim_start_time]  # seconds
    stim_end_times = [i / 1000 if i is not None else np.nan for i in print_variables_df.stim_end_time]  # seconds
    goals = print_variables_df.current_goal
    cue_times = session_df[session_df.content == "cue"].time.values
    reward_times = session_df[session_df.content == "reward"].time.values
    ITI_times = session_df[session_df.content == "ITI"].time.values[1:]  # session starts in ITI
    if len(cue_times) == len(reward_times) and len(cue_times) - 1 == len(ITI_times):
        ITI_times = np.append(ITI_times, session_end_time)
    elif len(cue_times) > len(ITI_times):
        cue_times = cue_times[:-1]
    trials_df = pd.DataFrame(
        {
            ("trial", ""): np.arange(1, len(cue_times) + 1),
            ("stim_trial", ""): stim_trials,
            ("trials_since_stim", ""): trials_since_stim,
            ("consecutive_stim_trials", ""): consecutive_stim_trials,
            ("goal", ""): print_variables_df.current_goal,
            ("errors", ""): _get_errors(session_df, goals, cue_times, reward_times),
            ("time", "stim_start"): stim_start_times,
            ("time", "cue"): cue_times,
            ("time", "stim_end"): stim_end_times,
            ("time", "reward"): reward_times,
            ("time", "end_reward_consumption"): _get_end_reward_consumption_times(
                session_df, goals, cue_times, reward_times, ITI_times, session_end_time
            ),
            ("time", "ITI_start"): ITI_times,
            ("time", "trial_end"): _get_trial_end_times(cue_times, ITI_times, session_end_time),
        }
    )
    trials_df.columns = pd.MultiIndex.from_tuples(trials_df.columns)
    return trials_df


