def get_pycontrol_sync_times(pycontrol_path):
    """
    Function to extract sync times from pycontrol data.
    Args:
        pycontrol_path (Path): Path to pycontrol data file
    Returns:
        sync_times (np.array): Array of sync times in seconds
            from start of session
    """
    raw_pycontrol_df = pd.read_csv(pycontrol_path, sep="\t")
    return raw_pycontrol_df[raw_pycontrol_df["subtype"] == "sync"].time.to_numpy()


